    def generate_suite(self, output_path: Optional[str] = None) -> List[AdversarialTestProblem]:
        problems = []
        for i, item in enumerate(self.CANONICAL_CONFLICT_CLAUSES):
            p = AdversarialTestProblem(
                id=f"cdcl_adv_{i+1:03d}",
                domain=item["domain"],
                target_conflict_clause=item["clause"],
                problem_text=item["problem"],
                expected_ground_truth=item["ground_truth"],
                trap_hypotheses=item["traps"],
                verification_method=item["verification"]
            )
            problems.append(p)
        
        if output_path:
            with open(output_path, "w", encoding="utf-8") as f:
                json.dump([dataclasses.asdict(p) for p in problems], f, indent=2, ensure_ascii=False)
            print(f"Generated {len(problems)} CDCL adversarial problems saved to {output_path}")
        
        return problems


