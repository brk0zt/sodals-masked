/// Training configuration
#[derive(Debug, Clone)]
pub struct TrainingConfig {
    pub learning_rate: f64,
    pub batch_size: usize,
    pub num_epochs: usize,
    pub lambda_magnitude: f64, // Weight for magnitude loss
    pub device: Device,
    pub checkpoint_interval: usize,
}

impl Default for TrainingConfig {
    fn default() -> Self {
        Self {
            learning_rate: 1e-4,
            batch_size: 32,
            num_epochs: 1000,
            lambda_magnitude: 0.5,
            device: Device::Cpu,
            checkpoint_interval: 100,
        }
    }
}

/// Training dataset: word -> (QYPTOS wave, Qwen embedding)
///
/// CRITICAL: Both sides of this dataset must contain REAL signals:
///   - Waves: From actual PhysicsNeuron simulation (not hash placeholders)
///   - Embeddings: From frozen Qwen embed_tokens layer (not hash placeholders)
///
/// Training on fake data produces a projector that aligns noise to noise.
pub struct AlignmentDataset {
    /// Input: Complex-valued semantic waves from QYPTOS
    waves: Vec<SemanticWave>,
    
    /// Target: Real-valued embeddings from frozen Qwen
    embeddings: Vec<Vec<f64>>,
    
    /// Vocabulary: words corresponding to each sample
    words: Vec<String>,
}

impl AlignmentDataset {
    /// Create dataset from pre-computed real data.
    ///
    /// This is the ONLY constructor that should be used for actual training.
    /// Both `waves` and `embeddings` must come from real pipelines:
    ///   - `waves`: Generated by running words through PhysicsNeuron simulation
    ///   - `embeddings`: Extracted from frozen Qwen model's embed_tokens layer
    ///
    /// # Panics
    /// Panics if waves.len() != embeddings.len() != words.len()
    pub fn from_real_data(
        words: Vec<String>,
        waves: Vec<SemanticWave>,
        embeddings: Vec<Vec<f64>>,
    ) -> Self {
        assert_eq!(words.len(), waves.len(), "words and waves must have equal length");
        assert_eq!(words.len(), embeddings.len(), "words and embeddings must have equal length");
        info!("Created alignment dataset from REAL data: {} samples", words.len());
        Self { waves, embeddings, words }
    }

    /// Create dataset from vocabulary using SIMULATED signals.
    ///
    /// ⚠️ WARNING: This uses hash-based FAKE embeddings on the teacher side.
    /// The AdamW/backward_step loop will run, but the projector will align to noise.
    /// Use ONLY for testing that the training loop mechanics work.
    /// For real training, use `from_real_data()` with actual Qwen embeddings.
    #[cfg(test)]
    pub fn from_vocabulary_simulated(
        words: &[String],
        wave_dim: usize,
        embedding_dim: usize,
    ) -> anyhow::Result<Self> {
        tracing::warn!(
            "⚠️ Using SIMULATED data for alignment dataset. \
             Both teacher (embedding) and student (wave) sides are hash-based placeholders. \
             This is only valid for testing training loop mechanics, NOT for real alignment."
        );
        info!("Creating SIMULATED alignment dataset for {} words", words.len());
        
        let mut waves = Vec::new();
        let mut embeddings = Vec::new();

        for word in words {
            let wave = Self::generate_simulated_wave(word, wave_dim)?;
            waves.push(wave);

            let embedding = Self::generate_simulated_embedding(word, embedding_dim);
            embeddings.push(embedding);
        }

        Ok(Self {
            waves,
            embeddings,
            words: words.to_vec(),
        })
    }

    /// Generate a REAL semantic wave by running a word through PhysicsNeuron simulation.
    ///
    /// Uses the word's hash to seed deterministic initial conditions, then
    /// runs 50 steps of the actual PhysicsNeuron forward pass to reach steady state.
    /// The resulting wave captures genuine nonlinear dynamics, not random noise.
    pub fn generate_real_wave(word: &str, dim: usize) -> anyhow::Result<SemanticWave> {
        let hash = Self::hash_string(word);
        let base_freq = 1.0 + (hash % 10) as f64 * 0.1;
        let base_phase = (hash % 360) as f64 * std::f64::consts::PI / 180.0;

        let mut neurons = Vec::new();
        for i in 0..dim {
            let freq_offset = (i as f64 * 0.1) % 1.0;
            let mut neuron = PhysicsNeuron::new(0.1);
            neuron.param_a = base_freq + freq_offset;
            neurons.push(neuron);
        }

        let input_signal = num_complex::Complex64::new(
            base_phase.cos(),
            base_phase.sin(),
        );

        let mut states = Vec::new();
        for neuron in &mut neurons {
            // Run 50 steps (not 10) to reach genuine steady state
            for _ in 0..50 {
                neuron.forward(input_signal);
            }
            states.push(neuron.get_state());
        }

        Ok(SemanticWave::from_vec(states))
    }

    /// Extract a REAL embedding from a frozen Qwen model's embed_tokens layer.
    ///
    /// Requires a loaded tokenizer and embed_tokens module.
    /// Returns f64 embedding vector for the given word.
    pub fn extract_real_embedding(
        word: &str,
        tokenizer: &tokenizers::Tokenizer,
        embed_tokens: &dyn candle_core::Module,
        device: &Device,
    ) -> anyhow::Result<Vec<f64>> {
        let encoding = tokenizer.encode(word.to_string(), false)
            .map_err(|e| anyhow::anyhow!("Tokenizer error: {}", e))?;
        
        let token_ids = encoding.get_ids();
        if token_ids.is_empty() {
            return Err(anyhow::anyhow!("Word '{}' produced no tokens", word));
        }

        // Use first token for single-token words; average for multi-token words
        let input = Tensor::new(token_ids, device)?;
        let input = input.unsqueeze(0)?; // [1, seq_len]
        let embeddings = embed_tokens.forward(&input)?; // [1, seq_len, hidden_dim]
        
        // Average across token positions for multi-token words
        let mean_embedding = embeddings.mean(1)?; // [1, hidden_dim]
        let flat = mean_embedding.squeeze(0)?; // [hidden_dim]
        let embedding_f32: Vec<f32> = flat.to_vec1()?;
        
        Ok(embedding_f32.into_iter().map(|v| v as f64).collect())
    }

    /// SIMULATED wave generator — hash-based, for testing only.
    fn generate_simulated_wave(word: &str, dim: usize) -> anyhow::Result<SemanticWave> {
        Self::generate_real_wave(word, dim) // Uses PhysicsNeuron, at least the student side is real
    }

    /// SIMULATED embedding generator — hash-based FAKE, for testing only.
    ///
    /// ⚠️ This does NOT produce real Qwen embeddings.
    /// The values are deterministic sin() of hash, which has no semantic meaning.
    pub fn generate_simulated_embedding(word: &str, dim: usize) -> Vec<f64> {
        let hash = Self::hash_string(word);
        (0..dim)
            .map(|i| {
                let seed = hash.wrapping_add(i as u64);
                (seed as f64).sin() * 0.1
            })
            .collect()
    }

    /// Simple string hash for reproducibility
    fn hash_string(s: &str) -> u64 {
        use std::collections::hash_map::DefaultHasher;
        use std::hash::{Hash, Hasher};
        
        let mut hasher = DefaultHasher::new();
        s.hash(&mut hasher);
        hasher.finish()
    }

    /// Get batch for training
    pub fn get_batch(
        &self,
        batch_idx: usize,
        batch_size: usize,
    ) -> Option<Batch> {
        let start = batch_idx * batch_size;
        let end = (start + batch_size).min(self.waves.len());
        
        if start >= self.waves.len() {
            return None;
        }

        Some(Batch {
            waves: self.waves[start..end].to_vec(),
            embeddings: self.embeddings[start..end].to_vec(),
            words: self.words[start..end].to_vec(),
        })
    }

    pub fn num_batches(&self, batch_size: usize) -> usize {
        self.waves.len().div_ceil(batch_size)
    }
}

/// Single training batch
pub struct Batch {
    pub waves: Vec<SemanticWave>,
    pub embeddings: Vec<Vec<f64>>,
    pub words: Vec<String>,
}

/// Train holographic projector (Whitepaper II4.1)
/// 
/// Teacher-Student setup:
/// - Teacher: Frozen Qwen embeddings (ground truth)
/// - Student: SODALS projector (learnable)
/// - Loss: Cosine similarity + magnitude matching
pub fn train_alignment_layer(
    config: TrainingConfig,
    dataset: AlignmentDataset,
    checkpoint_path: Option<&Path>,
) -> anyhow::Result<HolographicProjector> {
    info!("Starting holographic alignment training");
    info!("Config: {:?}", config);

    let device = &config.device;
    
    // Setup model and optimizer
    let varmap = VarMap::new();
    let vb = VarBuilder::from_varmap(&varmap, DType::F64, device);

    let wave_dim = dataset.waves[0].len();
    let embedding_dim = dataset.embeddings[0].len();

    let projector = HolographicProjector::new(vb.clone(), wave_dim, embedding_dim)?;
    
    // Use AdamW (better than SGD for this task)
    let mut opt = AdamW::new(
        varmap.all_vars(),
        candle_nn::ParamsAdamW {
            lr: config.learning_rate,
            ..Default::default()
        },
    )?;

    info!("Model: {}D wave -> {}D embedding", wave_dim, embedding_dim);
    info!("Dataset: {} samples", dataset.waves.len());

    // Training loop
    let mut best_loss = f64::INFINITY;
    
    for epoch in 0..config.num_epochs {
        let mut epoch_loss = 0.0;
        let num_batches = dataset.num_batches(config.batch_size);

        for batch_idx in 0..num_batches {
            let batch = dataset.get_batch(batch_idx, config.batch_size)
                .expect("Batch index out of bounds");

            // Forward pass
            let loss = compute_batch_loss(
                &projector,
                &batch,
                config.lambda_magnitude,
                device,
            )?;

            // Backward pass
            opt.backward_step(&loss)?;

            epoch_loss += loss.to_scalar::<f64>()?;
        }

        epoch_loss /= num_batches as f64;

        // Logging
        if epoch % 10 == 0 {
            debug!("Epoch {}: loss={:.6}", epoch, epoch_loss);
        }

        if epoch % config.checkpoint_interval == 0 {
            info!("Epoch {}: loss={:.6}", epoch, epoch_loss);
            
            // Save best model
            if epoch_loss < best_loss {
                best_loss = epoch_loss;
                if let Some(path) = checkpoint_path {
                    save_checkpoint(&varmap, path)?;
                    info!("Saved checkpoint (loss={:.6})", best_loss);
                }
            }
        }
    }

    info!("Training complete. Best loss: {:.6}", best_loss);
    Ok(projector)
}

/// Compute loss for a batch (Whitepaper II4.2)
/// 
/// L_total = L_cos + IIIIL_mag
fn compute_batch_loss(
    projector: &HolographicProjector,
    batch: &Batch,
    lambda: f64,
    device: &Device,
) -> anyhow::Result<Tensor> {
    // Project waves to embeddings
    let pred = projector.project_batch(&batch.waves)?;
    
    // Stack target embeddings
    let target = stack_embeddings(&batch.embeddings, device)?;

    // Cosine similarity loss
    let pred_norm = pred.sqr()?.sum_keepdim(1)?.sqrt()?;
    let target_norm = target.sqr()?.sum_keepdim(1)?.sqrt()?;
    
    let pred_normalized = pred.broadcast_div(&pred_norm)?;
    let target_normalized = target.broadcast_div(&target_norm)?;
    
    let cosine_sim = (pred_normalized * target_normalized)?.sum(1)?;
    let l_cos = (1.0 - cosine_sim)?.mean_all()?;

    // Magnitude loss
    let mag_diff = (pred_norm - target_norm)?;
    let l_mag = mag_diff.sqr()?.mean_all()?;

    // Combined loss
    let loss = (l_cos + (lambda * l_mag)?)?;
    
    Ok(loss)
}

/// Stack embeddings into batch tensor
fn stack_embeddings(embeddings: &[Vec<f64>], device: &Device) -> anyhow::Result<Tensor> {
    let batch_size = embeddings.len();
    let dim = embeddings[0].len();
    
    let flat: Vec<f64> = embeddings.iter()
        .flat_map(|e| e.iter().copied())
        .collect();
    
    Tensor::from_vec(flat, (batch_size, dim), device).map_err(anyhow::Error::from)
}

/// Save checkpoint
fn save_checkpoint(varmap: &VarMap, path: &Path) -> anyhow::Result<()> {
    varmap.save(path)?;
    Ok(())
}

/// Load checkpoint
pub fn load_checkpoint(path: &Path, _device: &Device) -> anyhow::Result<VarMap> {
    let mut varmap = VarMap::new();
    varmap.load(path)?;
    Ok(varmap)
}

